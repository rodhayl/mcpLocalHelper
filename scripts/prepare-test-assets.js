#!/usr/bin/env node
/**
 * Prepare locally-generated assets required by the full test suite.
 *
 * These files are intentionally ignored from git, but some tests assert
 * they exist in the workspace for compatibility checks.
 */
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const repoRoot = path.resolve(__dirname, '..');

function readFile(filePath) {
  return fs.readFileSync(filePath, 'utf8');
}

function toRepoRelative(filePath) {
  return path.relative(repoRoot, filePath).replace(/\\/g, '/');
}

function ensureDir(dirPath) {
  fs.mkdirSync(dirPath, { recursive: true });
}

function writeIfChanged(filePath, content) {
  if (fs.existsSync(filePath) && readFile(filePath) === content) {
    return false;
  }
  ensureDir(path.dirname(filePath));
  fs.writeFileSync(filePath, content, 'utf8');
  return true;
}

function patchSettingsConfigJson(settingsText, mutator) {
  const match = settingsText.match(/^CONFIG_JSON=(.*)$/m);
  if (!match) {
    throw new Error('Missing CONFIG_JSON in settings file');
  }

  const json = JSON.parse(match[1]);
  mutator(json);

  return settingsText.replace(/^CONFIG_JSON=.*$/m, `CONFIG_JSON=${JSON.stringify(json)}`);
}

function normalizeWorkspaceForRootCompat(configJson) {
  if (configJson && typeof configJson === 'object') {
    if (!configJson.workspace || typeof configJson.workspace !== 'object') {
      configJson.workspace = {};
    }

    const workspace = configJson.workspace;
    const existingRoots = Array.isArray(workspace.roots) ? workspace.roots : [];
    const roots = existingRoots.map((value) => (value === '..' ? '.' : value));
    if (!roots.includes('.')) {
      roots.unshift('.');
    }
    workspace.roots = roots;
    workspace.defaultRoot = '.';

    if (configJson.policy && typeof configJson.policy === 'object') {
      const policy = configJson.policy;
      if (Array.isArray(policy.allowlistPaths)) {
        const allowlist = policy.allowlistPaths.map((value) => (value === '..' ? '.' : value));
        if (!allowlist.includes('.')) {
          allowlist.unshift('.');
        }
        policy.allowlistPaths = [...new Set(allowlist)];
      }
    }
  }
}

function ensureRootCompatSettings(canonicalRelativePath, rootRelativePath) {
  const sourcePath = path.join(repoRoot, canonicalRelativePath);
  const targetPath = path.join(repoRoot, rootRelativePath);
  const source = readFile(sourcePath);
  const patched = patchSettingsConfigJson(source, normalizeWorkspaceForRootCompat);
  const changed = writeIfChanged(targetPath, patched);
  console.log(`[prepare-test-assets] ${changed ? 'wrote' : 'kept'} ${rootRelativePath}`);
}

function ensureDistPackage() {
  execFileSync('node', ['scripts/generate_package_files.js', 'dist_package'], {
    cwd: repoRoot,
    stdio: 'inherit',
  });
  console.log('[prepare-test-assets] generated dist_package');
}

function loadToolSurface() {
  const distModulePath = path.join(repoRoot, 'dist', 'server', 'tool-discovery.js');
  if (!fs.existsSync(distModulePath)) {
    throw new Error('dist/server/tool-discovery.js is missing. Run build first.');
  }

  // eslint-disable-next-line @typescript-eslint/no-var-requires, global-require
  const mod = require(distModulePath);
  return {
    core: Array.isArray(mod.CORE_TOOLS) ? mod.CORE_TOOLS : [],
    agentOnly: Array.isArray(mod.AGENT_ONLY_TOOLS) ? mod.AGENT_ONLY_TOOLS : [],
  };
}

function ensureAgentsMdFixture() {
  const { core, agentOnly } = loadToolSurface();
  const agentsPath = path.join(repoRoot, '.mcp-local-llm', 'AGENTS.md');
  const content = [
    '# AGENTS.md - mcplocalllm',
    '',
    '## Tool Surface',
    '',
    `- **Core Tools**: ${core.map((name) => `\`${name}\``).join(', ')}`,
    `- **Agent-Only Tools**: ${agentOnly.map((name) => `\`${name}\``).join(', ')}`,
    '',
    'Generated by scripts/prepare-test-assets.js for local test parity.',
    '',
  ].join('\n');

  const changed = writeIfChanged(agentsPath, content);
  console.log(`[prepare-test-assets] ${changed ? 'wrote' : 'kept'} .mcp-local-llm/AGENTS.md`);
}

function main() {
  console.log('[prepare-test-assets] generating dist_package');
  ensureDistPackage();

  ensureRootCompatSettings('config/env-automated-tests.settings', 'env-automated-tests.settings');
  ensureRootCompatSettings('config/env-opencode-optimized.settings', 'env-opencode-optimized.settings');
  ensureAgentsMdFixture();
  console.log('[prepare-test-assets] prepared transient test assets');
}

main();
